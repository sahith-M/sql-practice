"""Generate PostgreSQL load scripts for the SPARCS de-identified inpatient CSV.

Usage (from the sql-practice folder, in Anaconda Prompt):
    python setup/build_load_sql.py data/sparcs_2023.csv

Reads the CSV header and a sample of rows, then writes:
    sql/00_create_raw.sql     raw table, every column TEXT (a load never fails on bad values)
    sql/01_load_raw.sql       psql \\copy of the whole file into the raw table
    sql/02_create_clean.sql   typed table sparcs.discharges built from the raw table
    sql/03_sanity_checks.sql  row counts and null counts per column

Only the Python standard library is used.
"""
import csv
import pathlib
import re
import sys

SAMPLE_ROWS = 200_000
INT_RE = re.compile(r"^-?\d+$")
NUM_RE = re.compile(r"^-?(\d+\.?\d*|\.\d+)$")
# Identifiers are labels, not measures: keep them as text even when they look numeric.
ID_HINTS = ("code", "_id", "id_", "number", "zip", "year")


def norm(name: str) -> str:
    s = re.sub(r"[^0-9a-zA-Z]+", "_", name.strip().lower()).strip("_")
    return "c_" + s if s[:1].isdigit() else s


def strip_num(v: str) -> str:
    return re.sub(r"[,$\s+]", "", v)


def infer(csv_path: pathlib.Path):
    with csv_path.open(newline="", encoding="utf-8-sig") as f:
        reader = csv.reader(f)
        header = next(reader)
        cols = [norm(h) for h in header]
        stats = [{"seen": 0, "int": True, "num": True, "plus": False, "lead0": False} for _ in cols]
        for i, row in enumerate(reader):
            if i >= SAMPLE_ROWS:
                break
            for s, v in zip(stats, row):
                v = v.strip()
                if not v:
                    continue
                s["seen"] += 1
                if "+" in v:
                    s["plus"] = True
                c = strip_num(v)
                if len(c) > 1 and c.startswith("0") and not c.startswith("0."):
                    s["lead0"] = True
                if not INT_RE.match(c):
                    s["int"] = False
                if not NUM_RE.match(c):
                    s["num"] = False
    types = []
    for col, s in zip(cols, stats):
        is_id = any(h in f"_{col}_" or col.endswith(h.strip("_")) for h in ID_HINTS)
        if s["seen"] == 0 or s["lead0"] or (is_id and not col.endswith("year")):
            types.append("text")
        elif s["int"]:
            types.append("integer")
        elif s["num"]:
            types.append("numeric")
        else:
            types.append("text")
    return header, cols, types, stats


def main():
    if len(sys.argv) != 2:
        sys.exit("Usage: python setup/build_load_sql.py data/sparcs_2023.csv")
    csv_path = pathlib.Path(sys.argv[1]).resolve()
    if not csv_path.exists():
        sys.exit(f"File not found: {csv_path}")
    out = pathlib.Path(__file__).resolve().parent.parent / "sql"
    out.mkdir(exist_ok=True)
    header, cols, types, stats = infer(csv_path)

    raw_cols = ",\n    ".join(f"{c} TEXT" for c in cols)
    (out / "00_create_raw.sql").write_text(
        "-- Generated by setup/build_load_sql.py. Raw landing table: everything TEXT.\n"
        "CREATE SCHEMA IF NOT EXISTS sparcs;\n"
        "DROP TABLE IF EXISTS sparcs.discharges;\n"
        "DROP TABLE IF EXISTS sparcs.sparcs_raw;\n"
        f"CREATE TABLE sparcs.sparcs_raw (\n    {raw_cols}\n);\n",
        encoding="utf-8",
    )

    p = csv_path.as_posix()
    (out / "01_load_raw.sql").write_text(
        "-- Generated by setup/build_load_sql.py. Run with psql (\\copy is a psql command).\n"
        f"\\copy sparcs.sparcs_raw FROM '{p}' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')\n",
        encoding="utf-8",
    )

    exprs = []
    for c, t, s in zip(cols, types, stats):
        if t == "text":
            exprs.append(f"NULLIF(TRIM({c}), '') AS {c}")
        else:
            exprs.append(f"NULLIF(regexp_replace({c}, '[,$ +]', '', 'g'), '')::{t} AS {c}")
            if s["plus"]:
                exprs.append(f"({c} LIKE '%+%') AS {c}_capped")
    sel = ",\n    ".join(exprs)
    (out / "02_create_clean.sql").write_text(
        "-- Generated by setup/build_load_sql.py. Typed table built from the raw one.\n"
        "-- Empty strings become NULL; numbers lose commas/$; values like '120 +' become 120\n"
        "-- with a <column>_capped flag so you know they were capped.\n"
        "DROP TABLE IF EXISTS sparcs.discharges;\n"
        f"CREATE TABLE sparcs.discharges AS\nSELECT\n    {sel}\nFROM sparcs.sparcs_raw;\n"
        "ANALYZE sparcs.discharges;\n",
        encoding="utf-8",
    )

    nulls = "\nUNION ALL\n".join(
        f"SELECT '{c}' AS column_name, '{t}' AS type, COUNT(*) FILTER (WHERE {c} IS NULL) AS null_rows FROM sparcs.discharges"
        for c, t in zip(cols, types)
    )
    (out / "03_sanity_checks.sql").write_text(
        "-- Generated by setup/build_load_sql.py. Both counts must match.\n"
        "SELECT 'raw' AS tbl, COUNT(*) AS row_count FROM sparcs.sparcs_raw\n"
        "UNION ALL\nSELECT 'clean', COUNT(*) FROM sparcs.discharges;\n\n"
        "-- Null count per column (high counts = redacted or missing data; note them in your README).\n"
        f"{nulls}\nORDER BY null_rows DESC;\n",
        encoding="utf-8",
    )

    print(f"Columns found: {len(cols)}")
    for h, c, t in zip(header, cols, types):
        print(f"  {h!r:45} -> {c:40} {t}")
    print(f"SQL files written to {out}")


if __name__ == "__main__":
    main()
